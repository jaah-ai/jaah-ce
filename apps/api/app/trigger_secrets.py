"""A trigger's signing secret — minted, sealed, opened and verified here and nowhere else.

The secret is the HMAC key a GitHub sender proves itself with, or a legacy webhook's HMAC key or bearer token (a
webhook now takes a Jaah API key, `trigger_intake._key_verdict`, and has no secret: `takes_secret`). It is generated by
Jaah, shown to a human once (`routes/triggers.py`), and stored as a tier-1 AES-256-GCM envelope
(`credential_crypto.seal`, the primitive `mfa` uses for its TOTP secrets) bound to the trigger's id by the
AAD, so a sealed value copied onto another row does not open.

`open_secret` is the SINGLE plaintext seam. Its callers are the ingress route's verification and the console's
one-time reveal; nothing else may hold the plaintext, and no runner ever sees it: it is never in a prompt,
task body, environment, artifact, log line, deliveries row or digest (R3, AC-3.3).
"""
from __future__ import annotations

import hashlib
import hmac
import secrets
from typing import Any, Mapping, Optional
from uuid import UUID

from app import credential_crypto
from app.triggers import (
    AUTH_BEARER,
    AUTH_GITHUB,
    AUTH_HMAC,
    GITHUB_SIGNATURE_HEADER,
    LEGACY_WEBHOOK_AUTHS,
    SIGNATURE_HEADER,
    SOURCE_GITHUB,
    SOURCE_WEBHOOK,
)

# 32 random bytes, URL-safe: long enough that guessing is not an attack, short enough to paste.
_SECRET_BYTES = 32
_TOKEN_BYTES = 32
_SIGNATURE_PREFIX = "sha256="


def webhook_auth(config: Optional[Mapping[str, Any]]) -> str:
    """A webhook trigger's stored scheme. A config saved before `auth` was written reads as `hmac`, its default then."""
    return str((config or {}).get("auth") or AUTH_HMAC)


def takes_secret(source_kind: str, config: Optional[Mapping[str, Any]]) -> bool:
    """Whether a trigger of `source_kind` with `config` proves its sender with a secret: GitHub always, a webhook
    only on a legacy scheme."""
    if source_kind == SOURCE_GITHUB:
        return True
    return source_kind == SOURCE_WEBHOOK and webhook_auth(config) in LEGACY_WEBHOOK_AUTHS


def _aad(trigger_id: UUID) -> bytes:
    return b"task-trigger-secret|" + str(trigger_id).encode()


def new_secret() -> str:
    return secrets.token_urlsafe(_SECRET_BYTES)


def new_ingress_token() -> str:
    """The opaque URL id. base64url, so it never contains '/' (the edge forwards a normalized path)."""
    return secrets.token_urlsafe(_TOKEN_BYTES)


def seal_secret(trigger_id: UUID, secret: str) -> dict:
    return credential_crypto.seal({"secret": secret}, aad=_aad(trigger_id))


def open_secret(trigger) -> str:
    """The plaintext secret of `trigger` (a `models.TaskTrigger`). Raises `ValueError` when the row has none
    or the envelope does not open under this key."""
    if not trigger.secret_sealed:
        raise ValueError(f"trigger {trigger.id} has no secret")
    return credential_crypto.unseal(trigger.secret_sealed, aad=_aad(trigger.id), label="task_triggers")["secret"]


def sign(secret: str, body: bytes) -> str:
    """The `X-Jaah-Signature-256` value a sender sends for `body`: `sha256=<hex HMAC-SHA256>`."""
    return _SIGNATURE_PREFIX + hmac.new(secret.encode(), body, hashlib.sha256).hexdigest()


def verify_signature(secret: str, body: bytes, header: str) -> bool:
    """Whether `header` is `sign(secret, body)`, compared in constant time."""
    return hmac.compare_digest((header or "").strip().encode(), sign(secret, body).encode())


def verify_bearer(secret: str, authorization: str) -> bool:
    """Whether `authorization` is `Bearer <secret>`, compared in constant time."""
    scheme, _, presented = (authorization or "").strip().partition(" ")
    if scheme.lower() != "bearer":
        # Still a constant-time comparison, so a wrong scheme costs what a wrong token does.
        hmac.compare_digest(b"x", b"y")
        return False
    return hmac.compare_digest(presented.strip().encode(), secret.encode())


def verify(auth: str, secret: str, body: bytes, headers) -> bool:
    """The scheme `auth` ('hmac', 'bearer' or 'github') against the request; `headers` is case-insensitive.
    GitHub signs exactly as we do, under its own header (`X-Hub-Signature-256`)."""
    if auth == AUTH_BEARER:
        return verify_bearer(secret, headers.get("authorization", ""))
    if auth == AUTH_GITHUB:
        return verify_signature(secret, body, headers.get(GITHUB_SIGNATURE_HEADER, ""))
    return verify_signature(secret, body, headers.get(SIGNATURE_HEADER, ""))
